using System.IO.Compression;
using Pardeh.Skinning.Model;

namespace Pardeh.Skinning.Wmp;

/// <summary>Loads Windows Media Player skins: .wmz archives or loose .wms files.</summary>
/// <remarks>Archives are untrusted: they're read into memory only (never extracted to disk) with size limits.</remarks>
public static class WmzLoader
{
    private const int MaxEntries = 4096;
    private const long MaxEntrySize = 64L * 1024 * 1024;
    private const long MaxTotalSize = 256L * 1024 * 1024;

    public static SkinPackage Load(string path)
    {
        var extension = Path.GetExtension(path);
        if (extension.Equals(".wms", StringComparison.OrdinalIgnoreCase))
            return LoadLooseWms(path);

        using var stream = File.OpenRead(path);
        return LoadArchive(stream, path);
    }

    public static SkinPackage LoadArchive(Stream stream, string sourcePath)
    {
        using var zip = new ZipArchive(stream, ZipArchiveMode.Read);
        if (zip.Entries.Count > MaxEntries)
            throw new InvalidDataException($"Skin has too many files ({zip.Entries.Count}).");

        var files = new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase);
        long total = 0;
        foreach (var entry in zip.Entries)
        {
            if (entry.FullName.EndsWith('/'))
                continue;
            if (entry.Length > MaxEntrySize)
                throw new InvalidDataException($"Skin file '{entry.FullName}' is too large.");
            total += entry.Length;
            if (total > MaxTotalSize)
                throw new InvalidDataException("Skin is too large.");

            using var entryStream = entry.Open();
            using var buffer = new MemoryStream((int)entry.Length);
            CopyLimited(entryStream, buffer, MaxEntrySize);
            files[SkinPackage.NormalizeName(entry.FullName)] = buffer.ToArray();
        }

        return Build(files, sourcePath);
    }

    /// <summary>Builds a skin from an already-parsed THEME node (e.g. a decoded compiled skin).</summary>
    public static SkinPackage FromNode(SkinNode theme, string sourcePath, Dictionary<string, byte[]>? files = null) =>
        new(sourcePath, theme, files ?? new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase));

    /// <summary>Builds a skin from in-memory files (e.g. a skin generated by the app).</summary>
    public static SkinPackage FromFiles(Dictionary<string, byte[]> files, string sourcePath) =>
        Build(new Dictionary<string, byte[]>(files, StringComparer.OrdinalIgnoreCase), sourcePath);

    private static SkinPackage LoadLooseWms(string wmsPath)
    {
        var directory = Path.GetDirectoryName(Path.GetFullPath(wmsPath))!;
        var files = new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase);
        long total = 0;
        foreach (var file in Directory.EnumerateFiles(directory, "*", SearchOption.AllDirectories).Take(MaxEntries))
        {
            var info = new FileInfo(file);
            if (info.Length > MaxEntrySize)
                continue;
            total += info.Length;
            if (total > MaxTotalSize)
                break;
            files[SkinPackage.NormalizeName(Path.GetRelativePath(directory, file))] = File.ReadAllBytes(file);
        }

        return Build(files, wmsPath, Path.GetFileName(wmsPath));
    }

    private static SkinPackage Build(Dictionary<string, byte[]> files, string sourcePath, string? preferredWms = null)
    {
        var wmsName = preferredWms
                      ?? files.Keys.FirstOrDefault(k => k.EndsWith(".wms", StringComparison.OrdinalIgnoreCase) && !k.Contains('/'))
                      ?? files.Keys.FirstOrDefault(k => k.EndsWith(".wms", StringComparison.OrdinalIgnoreCase))
                      ?? throw new InvalidDataException("The skin has no .wms definition file.");

        var text = SkinPackage.DecodeText(files[wmsName]);
        var document = LenientXmlParser.Parse(text);
        var theme = document.Children.FirstOrDefault(n => n.Tag == "THEME")
                    ?? throw new InvalidDataException("The skin definition has no <THEME> element.");

        if (!theme.Children.Any(n => n.Tag == "VIEW"))
            throw new InvalidDataException("The skin has no <VIEW>.");

        return new SkinPackage(sourcePath, theme, files);
    }

    private static void CopyLimited(Stream source, Stream destination, long limit)
    {
        var buffer = new byte[81920];
        long copied = 0;
        int read;
        while ((read = source.Read(buffer, 0, buffer.Length)) > 0)
        {
            copied += read;
            if (copied > limit)
                throw new InvalidDataException("Skin file is larger than declared.");
            destination.Write(buffer, 0, read);
        }
    }
}
